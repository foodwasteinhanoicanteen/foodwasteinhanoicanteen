/* Who is asking: team/kitchen staff (PIN from .env) and an anonymous browser id for students.
   shortcut: a shared PIN and a browser-generated id instead of real accounts; fine for a local
   class pilot, upgrade to per-person logins before running it for the whole university. */
import { createHash, timingSafeEqual } from "node:crypto";
import type { IncomingMessage } from "node:http";
import { config } from "./config";
import { HttpError } from "./http";

const fails = new Map<string, { n: number; until: number }>();
const MAX_FAILS = 5, LOCK_MS = 10 * 60 * 1000;

const digest = (s: string) => createHash("sha256").update(s).digest();
const ip = (req: IncomingMessage) => req.socket.remoteAddress || "?";

/** True if the request carries the right staff PIN. Wrong PINs are counted and lock the address for 10 minutes. */
export function isStaff(req: IncomingMessage): boolean {
  const pin = String(req.headers["x-staff-pin"] || "");
  if (!pin) return false;
  const f = fails.get(ip(req));
  if (f && f.n >= MAX_FAILS && Date.now() < f.until) throw new HttpError(429, "Too many wrong PINs. Try again in 10 minutes.");
  if (!config.staffPin) return false;
  const ok = timingSafeEqual(digest(pin), digest(config.staffPin));
  if (ok) fails.delete(ip(req));
  else fails.set(ip(req), { n: (f && Date.now() < f.until ? f.n : 0) + 1, until: Date.now() + LOCK_MS });
  return ok;
}

export function requireStaff(req: IncomingMessage) {
  if (!isStaff(req)) throw new HttpError(403, config.staffPin ? "Only the team can change this. Unlock edit mode with the PIN." : "Editing is off: set STAFF_PIN in .env and restart.");
}

/** Anonymous student id generated by the browser (stored in localStorage). */
export function clientId(req: IncomingMessage): string | null {
  const id = String(req.headers["x-client-id"] || "");
  return /^[A-Za-z0-9-]{8,64}$/.test(id) ? id : null;
}
